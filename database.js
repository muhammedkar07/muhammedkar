const fs = require('node:fs');
const path = require('node:path');
const { DatabaseSync } = require('node:sqlite');
const { Pool } = require('pg');

function postgresPlaceholders(sql) {
  let position = 0;
  return sql.replace(/\?/g, () => `$${++position}`);
}

class Database {
  constructor() {
    this.isPostgres = Boolean(process.env.DATABASE_URL);
    if (this.isPostgres) {
      this.pool = new Pool({
        connectionString: process.env.DATABASE_URL,
        max: 5,
        connectionTimeoutMillis: 10000,
        idleTimeoutMillis: 30000,
      });
    } else {
      const filename = path.resolve(process.env.SQLITE_PATH || path.join(__dirname, 'data', 'exam.db'));
      fs.mkdirSync(path.dirname(filename), { recursive: true });
      this.sqlite = new DatabaseSync(filename);
    }
  }

  adapter(client) {
    const query = (sql, params = []) => {
      if (this.isPostgres) {
        return (client || this.pool).query(postgresPlaceholders(sql), params);
      }
      return this.sqlite.prepare(sql);
    };

    return {
      get: async (sql, params = []) => {
        if (this.isPostgres) {
          const result = await query(sql, params);
          return result.rows[0];
        }
        return query(sql).get(...params);
      },
      all: async (sql, params = []) => {
        if (this.isPostgres) {
          const result = await query(sql, params);
          return result.rows;
        }
        return query(sql).all(...params);
      },
      run: async (sql, params = []) => {
        if (this.isPostgres) {
          const result = await query(sql, params);
          return { changes: result.rowCount, lastInsertRowid: Number(result.rows[0]?.id) };
        }
        const result = query(sql).run(...params);
        return { changes: Number(result.changes), lastInsertRowid: Number(result.lastInsertRowid) };
      },
    };
  }

  get(sql, params) {
    return this.adapter().get(sql, params);
  }

  all(sql, params) {
    return this.adapter().all(sql, params);
  }

  run(sql, params) {
    return this.adapter().run(sql, params);
  }

  async transaction(callback) {
    if (this.isPostgres) {
      const client = await this.pool.connect();
      try {
        await client.query('BEGIN');
        const result = await callback(this.adapter(client));
        await client.query('COMMIT');
        return result;
      } catch (error) {
        try {
          await client.query('ROLLBACK');
        } catch (rollbackError) {
          console.error('PostgreSQL rollback failed:', rollbackError);
        }
        throw error;
      } finally {
        client.release();
      }
    }

    this.sqlite.exec('BEGIN IMMEDIATE');
    try {
      const result = await callback(this.adapter());
      this.sqlite.exec('COMMIT');
      return result;
    } catch (error) {
      try {
        this.sqlite.exec('ROLLBACK');
      } catch (rollbackError) {
        console.error('SQLite rollback failed:', rollbackError);
      }
      throw error;
    }
  }

  async initialize() {
    if (this.isPostgres) {
      await this.pool.query(`CREATE TABLE IF NOT EXISTS questions (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        question TEXT NOT NULL,
        a TEXT NOT NULL,
        b TEXT NOT NULL,
        c TEXT NOT NULL,
        d TEXT NOT NULL,
        e TEXT NOT NULL,
        answer TEXT NOT NULL
      )`);
      await this.pool.query(`CREATE TABLE IF NOT EXISTS results (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        participant_no TEXT NOT NULL DEFAULT '',
        score INTEGER NOT NULL,
        correct INTEGER NOT NULL,
        wrong INTEGER NOT NULL,
        blank INTEGER NOT NULL,
        duration INTEGER NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        email TEXT NOT NULL DEFAULT '',
        email_key TEXT NOT NULL DEFAULT '',
        review_json TEXT NOT NULL DEFAULT ''
      )`);
      await this.pool.query("ALTER TABLE results ADD COLUMN IF NOT EXISTS review_json TEXT NOT NULL DEFAULT ''");
      await this.pool.query("CREATE UNIQUE INDEX IF NOT EXISTS idx_results_email_key ON results(email_key) WHERE email_key <> ''");
      return;
    }

    this.sqlite.exec(`CREATE TABLE IF NOT EXISTS questions (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      question TEXT NOT NULL,
      a TEXT NOT NULL,
      b TEXT NOT NULL,
      c TEXT NOT NULL,
      d TEXT NOT NULL,
      e TEXT NOT NULL,
      answer TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS results (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      name TEXT NOT NULL,
      participant_no TEXT NOT NULL DEFAULT '',
      score INTEGER NOT NULL,
      correct INTEGER NOT NULL,
      wrong INTEGER NOT NULL,
      blank INTEGER NOT NULL,
      duration INTEGER NOT NULL,
      created_at TEXT DEFAULT CURRENT_TIMESTAMP
    );`);

    const resultColumns = new Set(this.sqlite.prepare('PRAGMA table_info(results)').all().map((column) => column.name));
    for (const [name, definition] of [
      ['participant_no', "TEXT NOT NULL DEFAULT ''"],
      ['email', "TEXT NOT NULL DEFAULT ''"],
      ['email_key', "TEXT NOT NULL DEFAULT ''"],
      ['review_json', "TEXT NOT NULL DEFAULT ''"],
    ]) {
      if (!resultColumns.has(name)) {
        this.sqlite.exec(`ALTER TABLE results ADD COLUMN ${name} ${definition}`);
      }
    }
    this.sqlite.exec("CREATE UNIQUE INDEX IF NOT EXISTS idx_results_email_key ON results(email_key) WHERE email_key <> ''");
  }

  async close() {
    if (this.isPostgres) {
      await this.pool.end();
    } else {
      this.sqlite.close();
    }
  }
}

module.exports = Database;
